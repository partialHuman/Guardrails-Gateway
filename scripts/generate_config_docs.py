"""
Static configuration reference documentation generator for SentraGuard Lite.

Uses only the Python standard library and loads ``app/config_specs.py`` directly
via ``importlib.util.spec_from_file_location`` (with temporary ``sys.modules``
registration and guaranteed ``finally`` cleanup) so package initialization in
``app/__init__.py`` or runtime settings loading in ``app/config.py`` never runs.
"""

from __future__ import annotations

import argparse
import ast
import importlib.util
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DOCS_PATH = REPO_ROOT / "docs" / "configuration.md"
CONFIG_SPECS_PATH = REPO_ROOT / "app" / "config_specs.py"
CONFIG_MODULE_PATH = REPO_ROOT / "app" / "config.py"
SPECS_MODULE_NAME = "_sentraguard_config_specs"

_SUBSYSTEM_SECTIONS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("1. Authentication & Ingress Safety", ("Authentication & Ingress Safety",)),
    ("2. Request Sizing & Memory Bounds", ("Request Sizing & Memory Bounds",)),
    ("3. Tiered Rate Limiting & Proxy Trust", ("Tiered Rate Limiting & Proxy Trust",)),
    ("4. Distributed Redis Rate Limiting", ("Distributed Redis Rate Limiting",)),
    ("5. Loader & Runtime Control", ("Loader & Runtime Control",)),
    ("6. UI, CLI & Container Hosting", ("Web UI", "CLI & Container Hosting")),
)


def load_config_specs_module(specs_path: Path = CONFIG_SPECS_PATH) -> Any:
    """Safely load ``app/config_specs.py`` without importing ``app`` or ``app.config``."""
    spec = importlib.util.spec_from_file_location(SPECS_MODULE_NAME, specs_path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Unable to create module spec for {specs_path}")

    module = importlib.util.module_from_spec(spec)
    had_existing = SPECS_MODULE_NAME in sys.modules
    previous = sys.modules.get(SPECS_MODULE_NAME)

    sys.modules[SPECS_MODULE_NAME] = module
    try:
        spec.loader.exec_module(module)
    finally:
        if had_existing and previous is not None:
            sys.modules[SPECS_MODULE_NAME] = previous
        else:
            sys.modules.pop(SPECS_MODULE_NAME, None)

    return module


def extract_settings_field_names(config_path: Path = CONFIG_MODULE_PATH) -> tuple[str, ...]:
    """Extract typed ``Settings`` model field names via pure-stdlib AST inspection."""
    tree = ast.parse(config_path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name == "Settings":
            fields: list[str] = []
            for stmt in node.body:
                if (
                    isinstance(stmt, ast.AnnAssign)
                    and isinstance(stmt.target, ast.Name)
                    and stmt.target.id != "model_config"
                ):
                    fields.append(stmt.target.id)
            return tuple(fields)
    raise RuntimeError("Settings class not found during static AST verification")


def _escape_cell(text: str) -> str:
    """Escape pipe characters cleanly for Markdown table rendering."""
    return text.replace("|", "\\|")


def render_configuration_markdown(
    specs_path: Path = CONFIG_SPECS_PATH,
    config_path: Path = CONFIG_MODULE_PATH,
) -> str:
    """Render deterministic LF-normalized Markdown for ``docs/configuration.md``."""
    specs_module = load_config_specs_module(specs_path)
    specs = tuple(specs_module.CONFIG_SPECS)

    # Statically confirm 1:1 parity between mapped specs and AST-declared Settings fields
    # without executing app/config.py or reading process environment variables.
    ast_settings_fields = extract_settings_field_names(config_path)
    mapped_attrs = tuple(s.python_attr for s in specs if s.python_attr is not None)
    if set(mapped_attrs) != set(ast_settings_fields):
        raise RuntimeError("CONFIG_SPECS python_attr mapping diverges from Settings fields")

    lines: list[str] = [
        "# Configuration Reference",
        "",
        "<!-- Generated by scripts/generate_config_docs.py from app/config_specs.py. Do not edit manually. -->",
        "",
        (
            "SentraGuard Lite enforces **strict fail-fast configuration parsing**. If an environment variable "
            "is unparseable, malformed, or violates boundary or cross-field constraints, the gateway raises "
            "`app.config.ConfigError` at startup and refuses to run."
        ),
        "",
        "> [!IMPORTANT]",
        (
            "> Silently falling back to defaults for invalid security settings is dangerous. Unrecognized "
            "spellings for booleans, invalid numeric bounds, invalid Redis URIs, malformed "
            "`GUARDRAILS_ENV_FILE` syntax, or enabling authentication/Redis without credentials fail closed."
        ),
        "",
        "---",
        "",
        "## Configuration Variables Overview",
        "",
        (
            "| Environment Variable | Default | Type | Component | Required / Optional | "
            "Validation Constraints | Sensitive | Deprecated | Description |"
        ),
        "| :--- | :--- | :--- | :--- | :--- | :--- | :---: | :---: | :--- |",
    ]

    for spec in specs:
        sensitive_label = "Yes" if spec.sensitive else "No"
        deprecated_label = "Yes" if spec.deprecated else "No"
        lines.append(
            f"| `{spec.env_var}` "
            f"| `{_escape_cell(spec.default_display)}` "
            f"| `{_escape_cell(spec.type_display)}` "
            f"| {_escape_cell(spec.component)} "
            f"| {_escape_cell(spec.required_label)} "
            f"| {_escape_cell(spec.validation_rules)} "
            f"| {sensitive_label} "
            f"| {deprecated_label} "
            f"| {_escape_cell(spec.description)} |"
        )

    lines.extend(["", "---", "", "## Detailed Variable Specifications", ""])

    specs_by_section: dict[str, list[Any]] = {}
    for spec in specs:
        specs_by_section.setdefault(spec.section, []).append(spec)

    for heading, section_keys in _SUBSYSTEM_SECTIONS:
        lines.extend([f"### {heading}", ""])
        section_specs: list[Any] = []
        for key in section_keys:
            section_specs.extend(specs_by_section.get(key, ()))

        for spec in section_specs:
            lines.append(f"#### `{spec.env_var}`")
            lines.append(f"- **Default:** `{spec.default_display}`")
            lines.append(f"- **Type:** `{spec.type_display}`")
            lines.append(f"- **Component:** {spec.component}")
            lines.append(f"- **Required / Optional:** {spec.required_label}")
            lines.append(f"- **Validation Constraints:** {spec.validation_rules}")
            lines.append(f"- **Sensitive:** {'Yes (never logged or exposed)' if spec.sensitive else 'No'}")
            if spec.deprecated:
                lines.append("- **Deprecated:** Yes")
            lines.append(f"- **Description:** {spec.description}")
            lines.append("")

        lines.extend(["---", ""])

    lines.extend(
        [
            "## Explicit Environment File Precedence (`GUARDRAILS_ENV_FILE`)",
            "",
            "1. **Process Environment (`os.environ`)**: Highest precedence whenever a key is present (even if set to `\"\"` or whitespace-only, which resolves to the field default without falling back to the file).",
            "2. **Explicit `GUARDRAILS_ENV_FILE`**: Opt-in only; local `.env` files are never auto-discovered.",
            "3. **Application Defaults**: Applied when a variable is absent from both process environment and `GUARDRAILS_ENV_FILE`.",
            "",
            "## Streamlit UI Access Gate (`evaluate_gate`)",
            "",
            "| `GUARDRAILS_API_KEY` | `GUARDRAILS_UI_PASSWORD` | `GUARDRAILS_UI_ALLOW_ANONYMOUS` | UI Gate Decision | UI Behavior |",
            "| :---: | :---: | :---: | :---: | :--- |",
            "| Unset | *Any* | *Any* | `GATE_OPEN` | Unrestricted (API is unauthenticated). |",
            "| Set | Set | *Any* | `GATE_LOGIN` | Displays password login screen. |",
            "| Set | Unset | `true` | `GATE_OPEN_WARN` | Displays warning banner that access is anonymous. |",
            "| Set | Unset | `false` | `GATE_LOCKED` | **Default:** Refuses service and displays locked error screen. |",
            "",
            "Invalid non-empty values for `GUARDRAILS_UI_ALLOW_ANONYMOUS` fail validation via `parse_strict_bool()` and stop UI rendering safely without revealing the invalid raw value.",
        ]
    )

    return "\n".join(lines).replace("\r\n", "\n") + "\n"


def _parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate or verify docs/configuration.md from canonical configuration metadata."
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--write",
        action="store_true",
        help="Write generated Markdown deterministically with LF line endings.",
    )
    mode.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if docs/configuration.md differs from generated output.",
    )
    parser.add_argument(
        "--path",
        type=Path,
        default=DEFAULT_DOCS_PATH,
        help="Target Markdown path (defaults to docs/configuration.md).",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    rendered = render_configuration_markdown()
    target: Path = args.path

    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        with target.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(rendered)
        return 0

    if not target.exists():
        print(f"Configuration documentation missing: {target}", file=sys.stderr)
        return 1

    current = target.read_bytes().decode("utf-8")
    if current != rendered:
        print(
            f"Configuration documentation out of sync with app/config_specs.py: {target}. "
            "Run: python scripts/generate_config_docs.py --write",
            file=sys.stderr,
        )
        return 1

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
